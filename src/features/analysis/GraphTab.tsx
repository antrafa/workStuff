import { ExternalLink, Network } from 'lucide-react'
import { useEffect, useState } from 'react'
import { Empty, SkeletonRows } from '@/ui'
import { graphUrl } from './api'
import { tx } from '@/lib/i18n'

// Shows the graph graphify already generated in the project (graphify-out/graph.html). Generating it from
// the panel was left out: it needs the agent running commands, and the runner here is read-only.
export function GraphTab({ projectPath }: { projectPath: string }) {
  const [state, setState] = useState<'loading' | 'ok' | 'missing'>('loading')
  const url = graphUrl(projectPath)

  useEffect(() => {
    fetch(url).then(r => setState(r.ok ? 'ok' : 'missing'), () => setState('missing'))
  }, [url])

  if (state === 'loading') return <SkeletonRows rows={1} height={320} />
  if (state === 'missing') {
    return (
      <Empty icon={Network} title={tx({ en: 'This project has no graph', pt: 'Este projeto não tem grafo' })}>
        {tx({
          en: <>The knowledge graph is generated by graphify. Run <code className="inline">/graphify</code> in Claude Code inside the project (or <code className="inline">graphify extract .</code>) and it shows up here, from <code className="inline">graphify-out/graph.html</code>.</>,
          pt: <>O grafo de conhecimento é gerado pelo graphify. Rode <code className="inline">/graphify</code> no Claude Code dentro do projeto (ou <code className="inline">graphify extract .</code>) e ele aparece aqui, a partir de <code className="inline">graphify-out/graph.html</code>.</>,
        })}
      </Empty>
    )
  }
  return (
    <div className="stack">
      <div className="row">
        <span className="muted" style={{ fontSize: 12.5 }}>{tx({ en: 'the project\'s graphify-out/graph.html', pt: 'graphify-out/graph.html do projeto' })}</span>
        <div className="spacer" />
        <a className="btn btn-sm" href={url} target="_blank" rel="noopener noreferrer"><ExternalLink size={13} /> {tx({ en: 'Open in a tab', pt: 'Abrir em aba' })}</a>
      </div>
      {/* sandbox without allow-same-origin: the HTML comes from the project and cannot reach the panel */}
      <iframe className="graph-frame" src={url} sandbox="allow-scripts" title={tx({ en: 'The project\'s knowledge graph', pt: 'Grafo de conhecimento do projeto' })} />
    </div>
  )
}
